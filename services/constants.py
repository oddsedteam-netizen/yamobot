# ── Версия бота ───────────────────────────────────────────────
# 1.11.1: привязка ТГК — только владельцу или админу канала, канал, уже
# привязанный к другому человеку, не отдаём (см. handlers/channels.py).
# 1.11.0: раздел «📢 Мой ТГК» (reply-кнопка вместо «🧩 Эксп функций»), надёжная
# доставка сообщений с фото, устойчивый polling (services/polling.py), категория
# ПЗ в уведомлении и настройка «🏷 Уточнение категории» у бота.
# 1.21.0: диагностика перестала падать (child_manager внедряется диспетчером),
# приветствие с фото больше не теряет картинку из-за премиум-эмодзи, в профиле
# кнопки разложены парами + широкие «YID» и «Мои ссылки», «Отказ» остаётся под
# ПЗ после «Я беру», /smena убрана у админов и требует подтверждения у ПЗ.
# 1.21.1: кнопки «Отказ» перестали падать (ValueError на int("q")/int("cancel") —
# фильтры были startswith и перехватывали соседние формы); фото автоприветствия
# админа сохраняется и перезаливается дочерним ботом, а не отбрасывается.
# 1.22.0: напоминалка научилась «заглушать» отдельные ПЗ («🔇 Заглушить» в
# уведомлении: навсегда или на сутки) и сбрасывать отсчёт («♻️ Сбросить»),
# чтобы накопившиеся напоминания не вываливались разом после перерыва.
# Закрытые/удалённые топики исключаются из напоминаний по мягкой метке
# closed_at — запись ПЗ и её история НЕ удаляются, а при forum_topic_reopened
# напоминания возвращаются. Служебные сообщения форума больше не уходят в ПЗ
# пользователю как обычные реплики админа.
# 1.30.0: «Поиск» в YID — анкеты бота и админа, ленты анкет, приглашения и
# отклики с одобрением/отказом, счётчики просмотров и суточный лимит рассылки;
# рейтинг админов и ботов (топ-20, динамический, без кэша) с кнопкой «вне
# рейтинга»; «Мои уведомления» — отключение уведомлений о новых ПЗ и
# напоминаний по конкретным ботам (жалоба: от поддержки и анкетниц в чате
# админов уведомления не нужны); удаление админа наконец спрашивает про
# рассылку по его ПЗ на ЛЮБОМ пути (карточка, ввод тега, админ вышел из чата)
# и освобождает его ПЗ, чтобы они не висели на несуществующем админе.
# 1.32.0: починены «мёртвые» кнопки — у хендлера «Просмотр профилей» было
# оборвано тело (экран не рисовался, в логах тишина), добавлен сканер кнопок без
# обработчика; в админ-панели появился раздел «Рейтинг» с ручным удалением
# админов и ботов из топа (решение админа, кнопка «Вернуть меня в рейтинг» его
# не перебивает); кнопка «👤 Профиль+» открывает профиль человека в боте
# (deep-link), в том числе из поиска по YID; в «Просмотре профилей» кнопка
# «🚫 Разбанить» снимает бан во всех ботах разом; в настройках ссылок — ТГК и
# Чат, которые зелёным рядом появляются в приветствии под FAQ и обучением;
# кнопки в YID переставлены по приоритету.
# 1.32.0 (доп.): починено «мёртвое» приглашение — в личку уходило сообщение с
# одной кнопкой «Открыть анкету», поэтому принять или отклонить его было
# НЕЧЕМ; добавлены «✅ Принять»/«❌ Отклонить» прямо в приглашении и раздел
# «📨 Приглашения» со всеми неотвеченными, при принятии владельцу уходит
# юзернейм и ID согласившегося; кнопки «🔎 Поиск» переставлены (обе анкеты
# широкими зелёными строками, «Приглашения» синим рядом с «Просмотр ботов»);
# кнопка «👤 Владелец бота» заменена на «👤 Профиль+» — развилка «боты / ВЛД»
# с полным профилем владельца (отвязка чатов по одному, удаление ботов, бан);
# при отказе от приглашения «Вы отклонили приглашение» уходило владельцу, хотя
# отказал админ, а самому админу не приходило ничего — теперь уведомление о
# решении всегда уходит тому, кто нажал кнопку, а владелец получает своё;
# починен «⏭ Пропустить»: на этот callback_data висело ДВА обработчика (по
# одному на каждую анкету), и aiogram выполнял только первый — обработчик
# анкеты админа был недостижим, а пропуск в анкете админа выбрасывал в меню.
# Теперь шаги обеих анкет описаны одной таблицей, и пропуск идёт строго на
# один шаг вперёд; пауза после отказа снижена с суток до 3 часов.
