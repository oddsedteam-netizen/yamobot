"""Определение «пиарных» обращений в ПЗ.

Иногда пользователь пишет боту не с вопросом или жалобой, а с предложением
рекламы («пиар») или взаимной рекламы («ВП» — взаимный пиар). Такие ПЗ полезно
помечать сразу при создании: админ видит в шапке топика (и в уведомлении о
новом ПЗ) пометку «возможно пиар» / «возможно ВП» и быстрее понимает, что за
обращение.

Определение работает по ПЕРВОМУ сообщению ПЗ (текст или подпись к медиа):
предложение пиара/ВП обычно пишут именно там. Формулировка «возможно»
специально мягкая — это подсказка админу, а не приговор.
"""

import re

# Что показываем админу.
PROMO_VP = "возможно ВП"
PROMO_PR = "возможно пиар"

# ── Взаимный пиар (ВП) ────────────────────────────────────────────────
# Отдельные «слова»-маркеры: «вп», «взаимопиар».
_VP_TOKENS = frozenset({"вп", "взаимопиар", "вп-", "-вп"})
# Фразы: «взаимный пиар», «взаимная реклама», «обмен постами», «бартер».
_VP_PHRASES = re.compile(
    r"взаимн\w*\s*(?:пиар|пр|пз|пост|реклам|ссылк|поддержк|подписчик)\w*"
    r"|обмен\w*\s*(?:пост|реклам|ссылк|подписчик|баннер)\w*"
    r"|бартер\w*",
    re.IGNORECASE,
)

# ── Пиар / реклама ────────────────────────────────────────────────────
# Отдельные «слова»-маркеры: «пиар», «pr», «промо».
_PROMO_TOKENS = frozenset({"пиар", "пр", "pr", "промо", "пиарчик"})
# Фразы: «пиар», «реклама», «продвижение», «разместить рекламу» и т.п.
_PROMO_PHRASES = re.compile(
    r"пиар\w*|реклам\w*|продвижен\w*|пропиар\w*|промо\w*"
    r"|разместить\s+(?:реклам|пост|ссылк|ваш)\w*"
    r"|предложение\s+по\s+реклам\w*",
    re.IGNORECASE,
)

# Разделитель «слов»: всё, что не буква/цифра/подчёркивание.
_SPLIT_RE = re.compile(r"[^\w]+", re.UNICODE)


def _tokens(text: str) -> list[str]:
    """Разбивает текст на слова (в нижнем регистре) для точечного поиска."""
    return [t for t in _SPLIT_RE.split(text) if t]


def detect_promo_intent(text: str | None) -> str | None:
    """Возвращает пометку для ПЗ или None, если это не похоже на пиар/ВП.

    ``PROMO_VP`` («возможно ВП») имеет приоритет: во взаимном пиаре слово
    «пиар» тоже встречается, но админу важнее видеть именно ВП.
    """
    raw = (text or "").strip()
    if not raw:
        return None
    low = raw.lower()
    tokens = _tokens(low)

    if any(t in _VP_TOKENS for t in tokens) or _VP_PHRASES.search(low):
        return PROMO_VP
    if any(t in _PROMO_TOKENS for t in tokens) or _PROMO_PHRASES.search(low):
        return PROMO_PR
    return None


def detect_promo_from_message(text: str | None, caption: str | None = None) -> str | None:
    """Пометка по первому сообщению ПЗ: учитывает и текст, и подпись к медиа."""
    return detect_promo_intent(text) or detect_promo_intent(caption)